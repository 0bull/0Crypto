// The trail's final frame (frame 360) as plain SVG, and the CSS that pins the HTML labels
// onto the boxes. Both come from the same geometry as the Lottie compositions.

import {
  ALPHA,
  CANVAS,
  COLORS,
  cutBox,
  geometry,
  LAYOUTS,
  lerp,
  linkEnds,
  NODE_IDS,
  STYLE,
  type Box,
  type Layout,
  type Point,
} from "./geometry.ts";

const n = (v: number): string => String(Math.round(v * 1000) / 1000);

function rect(b: Box, fill: string, fillOpacity: number, stroke: string, strokeOpacity: number): string {
  return (
    `<rect x="${n(b.x)}" y="${n(b.y)}" width="${n(b.w)}" height="${n(b.h)}" rx="${STYLE.radius}"` +
    ` fill="${fill}" fill-opacity="${fillOpacity}" stroke="${stroke}" stroke-opacity="${strokeOpacity}" stroke-width="${STYLE.boxStroke}"/>`
  );
}

function line(a: Point, b: Point, attrs: string): string {
  return `<line x1="${n(a[0])}" y1="${n(a[1])}" x2="${n(b[0])}" y2="${n(b[1])}" ${attrs}/>`;
}

export function buildStaticSvg(layout: Layout): string {
  const g = geometry(layout);
  const { w, h } = CANVAS[layout];
  const red = `stroke="${COLORS.line}" stroke-opacity="${ALPHA.line}" stroke-width="${STYLE.line}" stroke-linecap="round"`;
  const parts: string[] = [];

  for (const id of NODE_IDS) {
    const b = g.nodes[id];
    parts.push(
      id === "you"
        ? rect(b, COLORS.you, ALPHA.youFill, COLORS.you, ALPHA.youStroke)
        : rect(b, COLORS.white, ALPHA.boxFill, COLORS.white, ALPHA.boxStroke),
    );
  }

  for (const [from, to] of g.links) {
    const [a, b] = linkEnds(layout, g.nodes[from], g.nodes[to]);
    if (to !== "you") {
      parts.push(line(a, b, red));
      continue;
    }
    const cut = lerp(a, b, g.snapAt);
    parts.push(
      line(
        cut,
        b,
        `stroke="${COLORS.white}" stroke-opacity="${ALPHA.remainder}" stroke-width="${STYLE.line}" stroke-dasharray="${STYLE.dash.join(" ")}"`,
      ),
    );
    parts.push(line(a, cut, red));
  }

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" fill="none" aria-hidden="true" focusable="false">` +
    parts.join("") +
    `</svg>\n`
  );
}

const pc = (v: number, total: number): string => `${Math.round((v / total) * 1e6) / 1e4}%`;

export function buildGeometryCss(): string {
  const out = ["/* Generated by scripts/build-trail.ts from scripts/trail/geometry.ts. Do not edit. */"];
  for (const layout of LAYOUTS) {
    const { w, h } = CANVAS[layout];
    const g = geometry(layout);
    out.push(`.trail--${layout} { aspect-ratio: ${w} / ${h}; }`);
    const place = (b: Box) =>
      `{ left: ${pc(b.x, w)}; top: ${pc(b.y, h)}; width: ${pc(b.w, w)}; height: ${pc(b.h, h)}; }`;
    for (const id of NODE_IDS) out.push(`.trail--${layout} .trail__label--${id} ${place(g.nodes[id])}`);
    out.push(`.trail--${layout} .trail__cut ${place(cutBox(layout))}`);
  }
  return out.join("\n") + "\n";
}
