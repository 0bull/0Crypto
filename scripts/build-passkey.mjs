// Bundles client/admin-passkey.ts (with @simplewebauthn/browser) into the committed public/admin-passkey.js.
// `--out <file>` builds elsewhere so a test can compare bytes.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "rolldown";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const i = process.argv.indexOf("--out");
const out = i >= 0 && process.argv[i + 1] ? resolve(process.argv[i + 1]) : join(root, "public", "admin-passkey.js");

const BANNER = "/* Generated by scripts/build-passkey.mjs from client/admin-passkey.ts; do not edit. */";

// The library's two deprecation warnings end in a docs URL; drop it so the shipped file carries no external URL.
const stripDocsUrls = {
  name: "strip-docs-urls",
  transform(code, id) {
    if (!id.includes("@simplewebauthn")) return null;
    return code.replace(/\s*See https?:\/\/[^\s'"`]+/g, "");
  },
};

await build({
  plugins: [stripDocsUrls],
  input: join(root, "client", "admin-passkey.ts"),
  cwd: root,
  platform: "browser",
  logLevel: "warn",
  output: {
    file: out,
    format: "iife",
    minify: true,
    banner: BANNER,
  },
});
// Minification may drop plain comments; make sure the marker is there, once.
const built = readFileSync(out, "utf8");
if (!built.startsWith(BANNER)) writeFileSync(out, BANNER + "\n" + built);
console.log("built", out);
